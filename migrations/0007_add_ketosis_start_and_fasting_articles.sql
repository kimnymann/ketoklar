## Kold tyrker: den direkte vej

Her sænker du kulhydratindtaget til dit valgte keto-niveau fra første dag, ofte omkring 20–50 gram samlet kulhydrat dagligt. Fordelen er en enkel regel og ofte hurtigere målbar ketose. Ulempen er, at hovedpine, svimmelhed, træthed, forstoppelse, kvalme og nedsat træningspræstation kan føles mere markante.

En praktisk syvdages start:

- **Før dag 1:** Planlæg tre enkle måltider, køb ind, og fjern de mest oplagte fristelser fra køkkenbordet.
- **Dag 1–3:** Spis regelmæssigt og nok. Prioritér protein, grøntsager med få kulhydrater og almindelige fedtkilder. Det er ikke nødvendigt også at faste.
- **Dag 2–4:** Forvent, at vægten kan falde hurtigt på grund af tab af glykogen og vand. Det er ikke det samme som tilsvarende fedttab.
- **Dag 4–7:** Justér portionsstørrelse og grøntsager efter appetit og mave. Hold træningen lettere, hvis præstationen midlertidigt falder.
- **Efter uge 1:** Vurder søvn, energi, fordøjelse, sult og gennemførlighed — ikke kun vægten eller en ketonmåling.

Kold tyrker passer bedst til den raske voksne, der foretrækker klare regler, har tid til at planlægge og ikke bruger medicin, som påvirkes af et hurtigt fald i kulhydratindtaget.

## Gradvis nedtrapning: den rolige vej

Her reducerer du kulhydrat over to til fire uger. Fordelen er, at du kan lære nye måltider ét ad gangen og lettere opdage, hvad der giver symptomer. Ulempen er, at reglerne kræver flere beslutninger, og at målbar ketose kommer senere.

Et forslag over tre uger:

- **Uge 1:** Fjern sodavand, juice, slik og de fleste søde snacks. Behold dine normale hovedmåltider, men tilføj protein og grønt, så du ikke blot fjerner energi.
- **Uge 2:** Udskift brød, ris, pasta og kartofler i ét måltid ad gangen. Start med det måltid, der er lettest i din hverdag.
- **Uge 3:** Gør alle hovedmåltider kulhydratfattige, og brug eventuelt en kostregistrering i få dage til at finde skjulte kulhydrater.
- **Uge 4 efter behov:** Sænk yderligere mod 20–50 gram dagligt, hvis målet er ernæringsketose, og du endnu ikke er der.

Gradvis nedtrapning er ofte et godt valg, hvis du har en travl familiehverdag, tidligere har opgivet stramme kure, træner hårdt, er ældre eller let får maveproblemer. Det er også den mest forsigtige retning, hvis du ikke ved, hvordan kroppen reagerer — men medicin skal stadig håndteres sammen med en fagperson.

## Hvad sker der i kroppen de første uger?

Når kulhydrat falder, bruges leverens glykogenlager, og vandet, som er bundet til glykogen, frigives. Samtidig kan nyrerne udskille mere natrium og væske. Det forklarer en del af det hurtige vægttab og nogle tilfælde af svimmelhed og hovedpine.

Leveren øger ketonproduktionen, men vævene skal også vænne sig til at bruge mere fedt og flere ketoner. Derfor kan en blodmåling vise ketose, før energi og træning føles normale. De hyppigst beskrevne startgener er forbigående, men forskningen i den såkaldte keto-influenza er uensartet, og ikke alle symptomer skyldes nødvendigvis ketose.

Store mængder fedt fra den ene dag til den anden kan give kvalme eller diarré. For lidt fiberrig grønt og væske kan give forstoppelse. Kvaliteten af kosten tæller fra dag ét: keto behøver ikke være en tallerken uden grøntsager.

## Skal man lytte til kroppen?

Ja — men oversæt signalerne til handling i stedet for at betragte alle gener som et bevis på, at kosten virker.

**Skru ned eller skift til gradvis opstart**, hvis du har vedvarende hovedpine, forstoppelse, dårlig søvn, tydeligt faldende humør, gentagne svimmelhedsanfald eller træning, der fortsat fungerer dårligt. Gå eventuelt fra et meget lavt niveau til moderat kulhydrat og vurder igen.

**Stop og kontakt læge**, hvis du får gentagen opkastning, besvimer, bliver forvirret, får hjertebanken, vedvarende stærke mavesmerter eller symptomer på lavt blodsukker. Ved diabetes og tegn på ketoacidose skal du søge akut hjælp.

**Skift mål**, hvis planen skaber overspisning, social isolation eller tvangspræget kontrol. Et moderat lavere kulhydratindtag, der kan holdes, kan være bedre end en ketogen kost, der konstant bryder sammen.

> At ændre strategi er ikke at fejle. Målet er en kost, der både er ernæringsmæssigt forsvarlig og realistisk at leve med.

## Har alderen noget at sige?

Alder alene afgør ikke, om keto er egnet. Det gør helbred, muskelmasse, medicin, appetit, nyrefunktion og evnen til at spise varieret.

Yngre raske voksne tåler ofte hurtige kostskift, men de kan stadig få gener. Gravide, ammende, børn og unge bør ikke begynde på en restriktiv ketogen kost uden relevant klinisk vejledning.

Hos ældre voksne er der ekstra grund til at beskytte muskelmasse og forebygge fald. Hurtigt væske- og blodtryksfald, lav appetit og utilstrækkeligt protein kan være et problem. En gradvis start, tilstrækkelig protein og energi, styrketræning efter evne samt kontrol af medicin og blodtryk er derfor særligt relevant. Skrøbelige eller undervægtige ældre bør ikke eksperimentere på egen hånd.

## Hvilken metode skal du vælge?

Vælg kold tyrker, hvis du er rask, motiveres af en klar grænse og har forberedt måltiderne. Vælg gradvis nedtrapning, hvis du vil prioritere tolerabilitet, læring og fleksibilitet. Du kan også begynde gradvist og afslutte med en tydelig keto-uge.

Vent med [periodisk faste eller ét måltid om dagen](/artikler/faste-typer-maaltider-og-laengere-faste), til den nye kost fungerer. Når man ændrer én ting ad gangen, er det lettere at forstå kroppens reaktion.

