## Skal man springe et måltid over — og hvilket?

Du behøver ikke springe et måltid over for at få et længere natligt fasteinterval. Et tidligere aftensmåltid og ingen sen snack kan være nok.

Hvis du vil fjerne ét måltid, så vælg ud fra både biologi og hverdag. Små kontrollerede studier tyder på, at et tidligt spisevindue kan give bedre blodsukker- og appetitrespons end at lægge al maden sent. Det taler for at afslutte spisningen tidligere og eventuelt springe aftensmad over. Studierne er dog små, og for mange mennesker er aftensmaden dagens vigtigste sociale måltid.

At springe morgenmaden over er ikke automatisk usundt, men det er heller ikke magisk. Hvis en sen frokost giver koncentrationsbesvær eller fører til ukontrolleret spisning om aftenen, er strategien dårlig for dig. Hvis en tidlig morgenmad ikke passer til din appetit, kan et senere første måltid fungere fint.

Et godt valg er det måltid, du kan undvære uden svimmelhed, overspisning, dårlig søvn eller konflikt med træning og medicin. Begynd eventuelt med 12:12 eller 14:10 i to uger, før du prøver 16:8.

## Ét måltid om dagen: kan OMAD anbefales?

Det er muligt at spise én gang dagligt, men muligt er ikke det samme som optimalt. Små randomiserede overkrydsningsstudier har fundet både ændringer, der kan se gunstige ud, og mindre gunstige reaktioner. I et otteugers studie gav ét dagligt aftenmåltid blandt andet højere fastende glukose og en mere langvarig glukosestigning end tre måltider, selv om kalorierne var de samme. Et andet, kort studie med 11 raske deltagere fandt øget fedtforbrænding uden dårligere fysisk præstation. Datagrundlaget er for lille til en bred anbefaling.

Den praktiske udfordring er at få nok protein, grøntsager, fibre, vitaminer og energi i ét måltid uden ubehag. Det er særlig vigtigt for ældre, fysisk aktive og personer med lille appetit, fordi protein fordelt over flere måltider kan gøre det lettere at dække behovet og støtte muskelmassen.

OMAD er et dårligt sted at starte, hvis du bruger blodsukkersænkende medicin, har tendens til overspisning, er undervægtig, gravid, ammer eller har en spiseforstyrrelse. For mange giver to næringsrige måltider inden for otte til ti timer næsten samme enkelhed med mindre pres på ét måltid.

## Kan man leve af flydende kost under en faste?

Ja, et menneske kan i en periode få næring gennem væske, hvis drikken er en **ernæringsmæssigt komplet kost** med energi, protein, essentielle fedtsyrer, vitaminer og mineraler. Men så er det en flydende diæt, ikke faste. Den kan bruges klinisk i bestemte situationer, men bør ikke improviseres med juice, kaffe, bouillon eller proteinpulver alene.

Hvis væsken ikke indeholder tilstrækkelig energi og næring, er der reelt tale om længere faste eller sult. Kroppen bruger glykogen, fedt og også protein fra fedtfri masse. Et syvdages studie viste betydelige systemiske ændringer og tab af fedtfri masse under vandfaste; deltagerne var nøje udvalgt og undersøgt. Det beviser, at kroppen kan gennemføre en uge, ikke at det er sikkert eller gavnligt for alle.

## En eller to uger uden mad: er det muligt?

Det er fysiologisk muligt for nogle voksne med tilstrækkelige energireserver, men risikoen er væsentligt større end ved 16:8. Mulige komplikationer omfatter dehydrering, lavt blodtryk, besvimelse, elektrolytforstyrrelser, urinsyrestigning, tab af fedtfri masse, rytmeforstyrrelser og problemer med medicin. Nyere data fra overvåget langvarig vandfaste har også vist øget systemisk inflammation og blodpladeaktivering, så fortællingen om en entydig helbredskur er ikke dækkende.

Genopstarten er en del af risikoen. Efter mere end fem dage med meget lidt eller ingen mad kan hurtig genintroduktion af energi udløse refeeding-problemer med farlige forskydninger i fosfat, kalium, magnesium og væske. Retningslinjer anbefaler langsom genoptrapning og klinisk overvågning hos personer i risiko.

> En uge eller to på vand eller tilfældige drikke bør ikke gennemføres uden lægelig vurdering og en plan for både overvågning og genopstart af mad.

## Hvem bør ikke faste på egen hånd?

Undlad faste eller få individuel faglig vurdering, hvis du:

- er gravid eller ammer, er barn eller ung, undervægtig, skrøbelig eller nyligt har tabt dig utilsigtet
- har eller har haft en spiseforstyrrelse
- har type 1-diabetes eller bruger insulin, sulfonylurinstof eller SGLT2-hæmmer
- har nyre-, lever- eller hjertesygdom, urinsyregigt, alvorlig infektion eller skal opereres
- tager medicin, der skal indtages med mad, eller medicin mod blodtryk og væskebalance
- udfører sikkerhedskritisk arbejde eller oplever besvimelse, forvirring eller nedsat reaktionsevne

Stop fasten og søg hjælp ved besvimelse, forvirring, vedvarende opkast, stærke mavesmerter, brystsmerter, markant hjertebanken eller tegn på meget lavt blodsukker.

## En mere forsigtig prøveplan

For en rask voksen kan denne rækkefølge gøre forsøget mere overskueligt:

- Start med 12 timers natlig faste i en uge.
- Prøv derefter 14:10 i en til to uger og behold to eller tre næringsrige måltider.
- Gå kun videre til 16:8, hvis energi, søvn, humør, træning og fordøjelse fungerer.
- Lad være med samtidig at starte hård keto, kalorieunderskud og intens træning.
- Vurder effekten efter fire uger. Hvis eneste resultat er mere sult og mindre livskvalitet, er der ingen præmie for at fortsætte.

