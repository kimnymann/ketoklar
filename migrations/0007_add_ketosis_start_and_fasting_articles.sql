Denne artikel handler om **ernæringsketose hos voksne**. Det er en normal stofskiftetilstand og ikke det samme som diabetisk ketoacidose, som er en akut og farlig syreforgiftning.

## Hvad sker der i kroppen?

Kulhydrat bliver normalt nedbrudt til glukose. En del bruges med det samme, og en del lagres som glykogen i lever og muskler. Når tilførslen af kulhydrat falder markant, falder insulinpåvirkningen, leverens glykogenlager bliver mindre, og kroppen frigiver flere fedtsyrer fra fedtvævet.

Leveren omdanner en del af fedtsyrerne til ketonstofferne beta-hydroxybutyrat (BHB), acetoacetat og acetone. De kan bruges som energi af blandt andet muskler og hjerne. Man holder ikke op med at bruge glukose; kroppen kan fortsat danne den mængde, visse væv behøver, blandt andet fra aminosyrer og glycerol. Du kan læse mere om brændstofskiftet i [hvorfor fedt ikke er din fjende](/artikler/hvorfor-fedt-er-din-ven).

En ofte brugt forskningsmæssig grænse for ernæringsketose er **BHB på mindst 0,5 mmol/L i blodet**. Tallet er ikke et kvalitetsstempel på kosten, og højere er ikke automatisk bedre.

## Sådan kommer man typisk i ketose

Mange opnår målbar ketose ved at holde det samlede kulhydratindtag omkring 20–50 gram dagligt. Nogle skal lavere, andre kan ligge højere. Grænsen påvirkes blandt andet af kropsstørrelse, aktivitet, insulinresistens, protein- og energiindtag og tidligere kost.

Et praktisk udgangspunkt er:

- Byg måltider omkring kød, fisk, æg eller en anden tydelig proteinkilde.
- Spis grøntsager med få kulhydrater, for eksempel kål, broccoli, squash, salat og svampe.
- Brug primært fedt fra olivenolie, avocado, nødder, frø og fisk, og suppler efter smag med mejeriprodukter og andre fedtkilder.
- Fjern først sukkerholdige drikke, slik, brød, ris, pasta og kartofler; de står normalt for den største kulhydratmængde.
- Drik efter tørst, og vær opmærksom på væske og salt, især de første dage. Har du nyre-, hjerte- eller blodtrykssygdom, skal ændringer i salt og væske aftales med en fagperson.

For nogle ses ketoner efter et døgn, mens andre bruger flere dage. Hvis du vil gøre overgangen mere overskuelig, kan du følge vores [guide til kold tyrker eller gradvis nedtrapning](/artikler/keto-for-begyndere-guide).

## Hvor lidt skal der til for at komme ud af ketose?

Der findes ikke ét antal gram, som gælder for alle. Et kulhydratrigt måltid kan få BHB til at falde i timer eller et døgn, men responsen afhænger af portionen, din aktivitet og din metaboliske situation. Hos nogle stopper en moderat mængde kulhydrat den målbare ketose; hos andre ses blot et midlertidigt fald.

Det vigtigste er derfor ikke, om en enkelt måling ligger på 0,4 eller 0,6 mmol/L. Se på mønstret over flere dage og på formålet med kosten. Ved medicinsk ketogen behandling, for eksempel epilepsi, skal mål og afvigelser aftales med behandlingsteamet. Ved almindeligt vægttab eller appetitstyring er efterlevelse, madkvalitet og trivsel som regel mere nyttige pejlemærker end at jagte et højt ketontal.

> Et enkelt måltid ødelægger ikke et forløb. Det kan afbryde den målbare ketose midlertidigt, men du kan vende tilbage til din plan ved næste måltid.

## Sådan kan du teste ketose

**Blodmåling af BHB** er den mest direkte metode og regnes som den bedste hjemmemåling. Den kræver et lille fingerprik og teststrimler. Mål på omtrent samme tidspunkt og under nogenlunde samme forhold, hvis du vil sammenligne dage.

**Urinstrimler** måler acetoacetat. De er billige, men påvirkes af væskeindtag og viser, hvad der er udskilt, ikke den aktuelle BHB-koncentration. Et studie fandt, at urinstrimler ofte overså mild ketose. De kan derfor give et groft fingerpeg i starten, men et negativt resultat udelukker ikke ketose.

**Åndemålere** måler acetone. De kræver ingen stik og kan bruges gentagne gange, men apparater og omregninger er ikke standardiserede på samme måde som blodmåling. Brug helst den samme enhed og se på udviklingen frem for et isoleret tal.

Du behøver ikke måle, hvis du trives, har et almindeligt kostmål og kan følge din plan uden tal. Måling er mest nyttig, når et tal besvarer et konkret spørgsmål.

## Ernæringsketose er ikke ketoacidose

Ved ernæringsketose er der tilstrækkeligt insulin til at holde ketonproduktionen reguleret, og blodets pH forbliver normal. Ved diabetisk ketoacidose mangler kroppen insulin, ketoner og syre ophobes, og tilstanden kræver akut behandling. SGLT2-hæmmere kan i sjældne tilfælde give ketoacidose uden meget højt blodsukker.

Søg akut hjælp ved kvalme eller opkast, mavesmerter, hurtig eller dyb vejrtrækning, udtalt sløvhed, forvirring eller frugtagtig ånde — især hvis du har diabetes, er syg eller tager en SGLT2-hæmmer. Brug ikke en artikel om kostketose til at vurdere mulig ketoacidose.

## Passer keto til alle?

Nej. Keto kan være en brugbar kostform for nogle, men den er ikke nødvendig for et godt helbred, og den bør tilpasses individet. Tal med læge eller klinisk diætist **før start**, hvis du:

- har type 1-diabetes, bruger insulin, sulfonylurinstof eller SGLT2-hæmmer
- er gravid eller ammer, er barn eller ung, eller har en aktiv eller tidligere spiseforstyrrelse
- har nyre-, lever-, bugspytkirtel- eller galdesygdom, porfyri eller en kendt forstyrrelse i fedtomsætningen
- er skrøbelig, undervægtig eller har tendens til dehydrering, lavt blodtryk eller nyresten
- tager blodtryksmedicin eller vanddrivende medicin, som kan kræve opfølgning

En velplanlagt keto-kost skal stadig levere protein, fibre, vitaminer og mineraler. Forstoppelse, hovedpine, svimmelhed og nedsat præstation kan opstå under tilvænningen. Ved vedvarende gener bør du skrue ned for restriktionen, skifte strategi eller få faglig hjælp.

## Hvad er næste skridt?

Hvis du vil prøve keto, så vælg først mellem [en hurtig eller gradvis opstart](/artikler/keto-for-begyndere-guide). Overvejer du at kombinere keto med færre måltider, så læs også [guiden til 16:8, OMAD og længere faste](/artikler/faste-typer-maaltider-og-laengere-faste). Keto og faste er to forskellige værktøjer; du behøver ikke bruge begge.

